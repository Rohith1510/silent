import fs from "node:fs";
import path from "node:path";
import solc from "solc";

export function compile() {
  const sources = {};
  function scan(dir) {
    for (const file of fs.readdirSync(dir, { withFileTypes: true })) {
      const name = path.join(dir, file.name).replaceAll("\\", "/");
      if (file.isDirectory()) scan(name);
      else if (name.endsWith(".sol"))
        sources[name] = { content: fs.readFileSync(name, "utf8") };
    }
  }
  scan("contracts");
  const output = JSON.parse(
    solc.compile(
      JSON.stringify({
        language: "Solidity",
        sources,
        settings: {
          optimizer: { enabled: true, runs: 200 },
          evmVersion: "paris",
          outputSelection: {
            "*": {
              "*": [
                "abi",
                "evm.bytecode.object",
                "evm.deployedBytecode.object",
              ],
            },
          },
        },
      }),
      {
        import: (name) => {
          try {
            return {
              contents: fs.readFileSync(
                path.join(
                  "node_modules",
                  name.replace(
                    "@openzeppelin/contracts@5.4.0/",
                    "@openzeppelin/contracts/",
                  ),
                ),
                "utf8",
              ),
            };
          } catch {
            return { error: `Missing import: ${name}` };
          }
        },
      },
    ),
  );
  const errors = output.errors?.filter((e) => e.severity === "error") ?? [];
  if (errors.length)
    throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
  return output.contracts;
}

if (process.argv[1]?.endsWith("compile.mjs")) {
  const contracts = compile();
  fs.mkdirSync("artifacts", { recursive: true });
  fs.mkdirSync("frontend/lib/generated", { recursive: true });
  fs.mkdirSync("cre/frontend-abi", { recursive: true });
  for (const [file, items] of Object.entries(contracts))
    for (const [name, artifact] of Object.entries(items)) {
      if (!file.startsWith("contracts/")) continue;
      const size = artifact.evm.deployedBytecode.object.length / 2;
      if (size > 24576)
        throw new Error(`${name} exceeds EIP-170 (${size} bytes)`);
      fs.writeFileSync(
        `artifacts/${name}.json`,
        JSON.stringify(artifact, null, 2),
      );
      if (
        [
          "SilentSovereignVault",
          "SilentSovereignFactory",
          "SilentSovereignCREReceiver",
        ].includes(name)
      ) {
        fs.writeFileSync(
          `frontend/lib/generated/${name}.ts`,
          `// Generated by npm run compile. Do not hand edit.\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
        );
        if (
          name === "SilentSovereignVault" ||
          name === "SilentSovereignFactory"
        )
          fs.copyFileSync(
            `frontend/lib/generated/${name}.ts`,
            `cre/frontend-abi/${name === "SilentSovereignVault" ? "vault" : "factory"}.ts`,
          );
      }
      console.log(`${name}: ${size} runtime bytes`);
    }
}
